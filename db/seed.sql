-- -------------------------------------------------------
-- 5. SEATS
-- Pattern per screen (total_seats N):
--   Rows A-B  → Regular   (seats per row = N/5, 2 rows)
--   Rows C-D  → Premium   (seats per row = N/5, 2 rows)
--   Row  V    → VIP       (remaining seats)
-- For simplicity we lock seat counts per the defined
-- screen capacities below using exact row/col combos.
-- -------------------------------------------------------

-- ============================================================
-- Seat generation helper notation used below:
--   Regular  → rows A, B
--   Premium  → rows C, D
--   VIP      → row  V
-- Counts are tuned so total matches screen capacity.
-- ============================================================

-- ---- Helper procedure to avoid 88 × repeat blocks --------
-- We use a stored procedure to insert seats dynamically.

DELIMITER $$

DROP PROCEDURE IF EXISTS sp_seed_seats $$

CREATE PROCEDURE sp_seed_seats(
    IN p_screen_id   INT,
    IN p_total_seats INT
)
BEGIN
    DECLARE cols        INT;
    DECLARE vip_cols    INT;
    DECLARE col         INT;
    DECLARE seat_label  VARCHAR(10);

    -- Divide capacity: 40% Regular (cols A+B), 40% Premium (C+D), 20% VIP (V)
    -- Regular rows A,B each get 20% of total => cols = total*0.2
    -- Premium rows C,D each get 20% of total => same cols
    -- VIP row V gets remaining 20%           => same cols
    SET cols     = FLOOR(p_total_seats * 0.20);
    SET vip_cols = p_total_seats - (cols * 4);  -- absorbs rounding

    -- Row A — Regular
    SET col = 1;
    WHILE col <= cols DO
        SET seat_label = CONCAT('A', col);
        INSERT INTO Seats (screen_id, seat_number, seat_type)
              VALUES (p_screen_id, seat_label, 'Regular');
        SET col = col + 1;
    END WHILE;

    -- Row B — Regular
    SET col = 1;
    WHILE col <= cols DO
        SET seat_label = CONCAT('B', col);
        INSERT INTO Seats (screen_id, seat_number, seat_type)
              VALUES (p_screen_id, seat_label, 'Regular');
        SET col = col + 1;
    END WHILE;

    -- Row C — Premium
    SET col = 1;
    WHILE col <= cols DO
        SET seat_label = CONCAT('C', col);
        INSERT INTO Seats (screen_id, seat_number, seat_type)
              VALUES (p_screen_id, seat_label, 'Premium');
        SET col = col + 1;
    END WHILE;

    -- Row D — Premium
    SET col = 1;
    WHILE col <= cols DO
        SET seat_label = CONCAT('D', col);
        INSERT INTO Seats (screen_id, seat_number, seat_type)
              VALUES (p_screen_id, seat_label, 'Premium');
        SET col = col + 1;
    END WHILE;

    -- Row V — VIP
    SET col = 1;
    WHILE col <= vip_cols DO
        SET seat_label = CONCAT('V', col);
        INSERT INTO Seats (screen_id, seat_number, seat_type)
              VALUES (p_screen_id, seat_label, 'VIP');
        SET col = col + 1;
    END WHILE;

END $$

DELIMITER ;

